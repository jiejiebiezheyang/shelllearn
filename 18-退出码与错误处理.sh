# 子 shell 因为 false 而中止，退出码 = 1
# 对比一下，不开启 set -e 的情况：
#   步骤 1：开始处理
#   步骤 2：出错了也照样往下跑
#
# ===== 小节 4：set -u 与 pipefail =====
#   set -u 已开启，引用不存在的变量会直接报错退出
# 引用未定义变量后，子 shell 退出码 = 1
