# 脚本正常结束时最好主动写一句 exit 0，让调用者明确知道结果
# 子 shell 用 exit 0 结束，父 shell 看到的退出码是 0
#
# ===== 小节 2：exit 提前结束脚本 =====
#   子 shell：第 1 步完成
#   子 shell：遇到严重错误，准备 exit 3
# 子 shell 的退出码是 3，父 shell 继续正常运行
#
# ===== 小节 3：set -e 出错即停 =====
#   步骤 1：开始处理
