#!/bin/bash
# ============================================
# 序号: 18
# 主题: 退出码与错误处理（exit、set -e、trap）
# 难度: ★★★
# 前置知识: 04 条件判断、10 函数定义与返回值
# 学习目标: 掌握 exit、set -e、set -u、pipefail 与 trap 的用法
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. 退出码：每条命令结束时都会留下一个 0-255 的数，$? 取到它。
#    0 = 成功，非 0 = 失败。if 判断的正是这个数。
# 2. exit N：立刻结束脚本，并把 N 作为脚本的退出码返回给调用者。
#    脚本正常跑完的退出码是最后一条命令的退出码，所以最好显式写 exit 0。
# 3. set -e：只要有任何一条命令失败（退出码非 0），脚本立刻中止。
#    好处是避免"前面错了后面还硬着头皮跑"，坏处是有些命令本来就允许失败，
#    这时用 `命令 || true` 放过它。
# 4. set -u：引用未定义的变量直接报错退出，能挡住拼错变量名的低级错误。
# 5. set -o pipefail：默认管道只看最后一个命令的退出码，
#    开启后管道中任何一环失败，整条管道就算失败。
# 6. 生产脚本的黄金开头：set -euo pipefail
# 7. trap：捕获信号或退出事件，做收尾工作（删临时文件、解锁、打印日志）。
#      trap '命令' EXIT   脚本任何方式退出都执行
#      trap '命令' INT    收到 Ctrl+C 时执行
#      trap - EXIT        取消捕获
# ------------------------------------------------------------

echo "===== 小节 1：退出码 \$? 与 return ====="
ok_func() { return 0; }               # 定义一个"成功"的函数
fail_func() { return 1; }             # 定义一个"失败"的函数
ok_func
echo "ok_func 之后的 \$? = $?（0 代表成功）"
fail_func
echo "fail_func 之后的 \$? = $?（非 0 代表失败）"
echo "脚本正常结束时最好主动写一句 exit 0，让调用者明确知道结果"
( exit 0 )                            # 放进子 shell 演示，不会真的终止本脚本
echo "子 shell 用 exit 0 结束，父 shell 看到的退出码是 $?"

echo
echo "===== 小节 2：exit 提前结束脚本 ====="
(                                     # 放进子 shell，避免真的终止本脚本
    echo "  子 shell：第 1 步完成"
    echo "  子 shell：遇到严重错误，准备 exit 3"
    exit 3                            # 立刻结束，后面的命令不再执行
    echo "  子 shell：这行永远不会被执行"
)
echo "子 shell 的退出码是 $?，父 shell 继续正常运行"

echo
echo "===== 小节 3：set -e 出错即停 ====="
(
    set -e                            # 开启"出错即停"
    echo "  步骤 1：开始处理"
    echo "  步骤 2：执行一条会失败的命令"
    false                             # 这里失败，脚本立刻中止
    echo "  步骤 3：你不会看到这一行"
)
echo "子 shell 因为 false 而中止，退出码 = $?"
echo "对比一下，不开启 set -e 的情况："
(
    echo "  步骤 1：开始处理"
    false                             # 失败但没人管
    echo "  步骤 2：出错了也照样往下跑"
)

echo
echo "===== 小节 4：set -u 与 pipefail ====="
( set -u; echo "  set -u 已开启，引用不存在的变量会直接报错退出" )
( set -u; echo "未定义变量的值是：$UNDEFINED_VAR_XYZ" ) 2>/dev/null   # 报错信息丢进黑洞
echo "引用未定义变量后，子 shell 退出码 = $?"
set +o pipefail                       # 先确保关闭，方便对比
false | true
echo "未开 pipefail：false | true 的退出码 = $?（只看最后一个命令）"
( set -o pipefail; false | true )
echo "开了 pipefail：同样管道的退出码 = $?（有一环失败就算失败）"

echo
echo "===== 小节 5：用 || true 放过允许失败的命令 ====="
(
    set -e                            # 严格模式
    grep '不存在的关键词' /etc/hostname > /dev/null 2>&1 || true   # 故意放过
    echo "  grep 没找到也没关系，脚本继续往下走"
)
echo "子 shell 顺利跑完，退出码 = $?"

echo
echo "===== 小节 6：trap 做收尾清理 ====="
tmpfile=$(mktemp)                     # 造一个临时文件
cleanup() {                           # 定义收尾函数
    echo "  [trap] 开始收尾：删除临时文件 $tmpfile"
    rm -f "$tmpfile"
    echo "  [trap] 收尾完成"
}
trap cleanup EXIT                     # 绑定到 EXIT：脚本怎么退出都会执行
trap 'echo "  [trap] 收到 Ctrl+C 信号，先清理再退出"' INT
echo "临时文件已创建：$tmpfile"
echo "脚本主体执行完毕，马上就要退出了"
echo "（注意看下一行：即使脚本正常结束，trap EXIT 也会触发）"

