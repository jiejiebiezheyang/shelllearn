#!/bin/bash
# ============================================
# 序号: 30
# 主题: 定时任务与 cron 综合案例
# 难度: ★★★
# 前置知识: 18 退出码与错误处理、26 日志分析与统计
# 学习目标: 掌握 crontab 时间格式、给 cron 写脚本的规范与防重叠锁
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. crontab 的时间格式是五个星号加一条命令：分 时 日 月 周 命令
#    · 分 0-59、时 0-23、日 1-31、月 1-12、周 0-7（0 和 7 都算周日）
#    · * 表示"每个"；*/5 表示"每 5 个单位"；1-5 是范围；1,3,5 是列举
# 2. 常用例子（记几个就够用了）：
#      0 3 * * *      每天凌晨 3:00        */5 * * * *   每 5 分钟
#      0 */2 * * *    每 2 小时            30 8 * * 1-5  周一到周五 8:30
#      0 0 1 * *      每月 1 号零点        @reboot       每次开机执行一次
# 3. crontab 管理命令：-l 列出、-e 编辑（保存即生效）、
#    -r 删除全部任务（危险！没有二次确认）。
# 4. 给 cron 写脚本的四条军规：
#    · 全部用绝对路径：cron 的 PATH 极简，command not found 是头号故障；
#    · 显式重定向输出：cron 会把输出发邮件，不想要就写 >> 日志 2>&1；
#    · 加锁防重叠：上一次没跑完下一次又被拉起，会互相踩踏（见小节 5）；
#    · 脚本开头写 set -euo pipefail，并自己打日志，方便事后排查。
# 5. flock 加锁套路：exec 9>"锁文件" 把 9 号描述符绑到锁文件，
#    再用 flock -n 9 非阻塞抢锁，抢不到就立刻返回失败。
# 6. cron 的坑还有：% 要转义成 \%、任务不会自动读 ~/.bashrc；
#    要精确到秒或依赖开机顺序，用 systemd timer 更合适。
# ------------------------------------------------------------

echo "===== 小节 1：crontab 时间格式图解 ====="
cat <<'EOF'
  ┌───────────── 分钟 (0-59)
  │ ┌─────────── 小时 (0-23)
  │ │ ┌───────── 日   (1-31)
  │ │ │ ┌─────── 月   (1-12)
  │ │ │ │ ┌───── 星期 (0-7，0 和 7 都是周日)
  │ │ │ │ │
  * * * * *   要执行的命令
EOF
echo "常见写法："
echo "  0 3 * * *      每天凌晨 3:00"
echo "  */5 * * * *    每 5 分钟"
echo "  0 */2 * * *    每 2 小时"
echo "  30 8 * * 1-5   周一到周五 8:30"
echo "  0 0 1 * *      每月 1 号零点"
echo "  @reboot        开机时执行一次"

echo
echo "===== 小节 2：crontab 管理命令 ====="
echo "  crontab -l   列出当前用户已有的定时任务"
echo "  crontab -e   编辑定时任务（保存即生效）"
echo "  crontab -r   删除全部定时任务（没有二次确认，慎用）"
echo "本脚本只做演示，不会真的修改你的 crontab"
if command -v crontab > /dev/null 2>&1; then
    echo "检测到本机有 crontab 命令：$(command -v crontab)"
else
    echo "本机没有 crontab 命令，可能需要先安装 cron 服务"
fi

echo
echo "===== 小节 3：准备一个「给 cron 用」的任务脚本 ====="
work=$(mktemp -d)                      # 实验目录（真实场景请用固定目录）
lockfile="$work/job.lock"              # 锁文件
logfile="$work/job.log"                # 日志文件

# 这个函数模拟"被 cron 定时拉起的那段任务代码"
run_job() {
    exec 9>"$lockfile"                 # 9 号描述符绑定锁文件
    if ! flock -n 9; then              # -n 非阻塞：抢不到锁说明上一次还在跑
        echo "$(date '+%F %T') [跳过] 上一次任务还没结束" | tee -a "$logfile"
        return 1                       # 返回非 0，告诉 cron 这次没干活
    fi
    echo "$(date '+%F %T') [开始] 采集数据并上报" >> "$logfile"
    sleep 0.2                          # 假装干了点活
    echo "$(date '+%F %T') [完成] 本次任务正常结束" >> "$logfile"
    return 0
}
echo "任务脚本已就绪，锁文件：$lockfile"
echo "真实使用时，crontab 里这样写（注意全部用绝对路径）："
echo "  */5 * * * * /usr/bin/bash /opt/scripts/job.sh >> /var/log/job.log 2>&1"

echo
echo "===== 小节 4：模拟 cron 连续触发 3 次 ====="
for i in 1 2 3; do
    echo "-- 第 $i 次触发 --"
    if run_job; then
        echo "   结果：执行成功"
    else
        echo "   结果：被跳过（上一次还没跑完）"
    fi
done

echo
echo "===== 小节 5：重点演示 —— 锁真的能防重叠 ====="
echo "-- 先在后台占住锁，模拟一个「跑得很慢」的任务 --"
(
    exec 9>"$lockfile"                 # 后台任务也抢同一把锁
    flock 9                            # 阻塞式抢锁，拿到就往下走
    sleep 1                            # 假装要跑 1 秒
) &
holder=$!                              # 记下后台任务的 PID
sleep 0.3                              # 等它确实把锁拿到手
echo "-- 此时 cron 又拉起一次任务，应该被拒绝 --"
if run_job; then
    echo "   结果：执行成功"
else
    echo "   结果：被跳过，退出码 $?（这就是防重叠的效果）"
fi
wait "$holder"                         # 等后台任务结束，锁自动释放
echo "-- 后台任务结束、锁释放之后，再触发一次 --"
if run_job; then
    echo "   结果：这次正常执行"
fi

echo
echo "===== 小节 6：查看任务日志 ====="
sed 's/^/  /' "$logfile"               # 给每行加缩进再打印
echo "日志总行数：$(wc -l < "$logfile")"
echo "（真实环境里可以用第 26 课的方法分析这个日志）"

echo
echo "===== 小节 7：cron 排错清单 ====="
cat <<'EOF'
  1. 命令写绝对路径：/usr/bin/bash、/bin/date，别指望 PATH
  2. 输出自己接住：>> /var/log/xxx.log 2>&1，否则会被当邮件发走
  3. 先用 bash -x 手动跑一遍脚本，确认不是脚本本身的问题
  4. 看系统日志：journalctl -u cron  或  tail /var/log/syslog
  5. crontab 里的 % 要写成 \%（它默认是换行符的特殊含义）
  6. 要精确到秒或依赖开机顺序，用 systemd timer 更合适
EOF

rm -rf "$work"                         # 清理实验目录
echo
echo "实验目录已清理"

