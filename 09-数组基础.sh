# ------------------------------------------------------------
# 【知识点讲解】
# 1. 定义数组：数组名=(值1 值2 值3)，元素之间用空格分隔。
#    想表达带空格的一个元素，就加引号："hello world"。
# 2. 下标从 0 开始：${数组[0]} 是第一个元素。
# 3. 常用写法（务必记牢这几个"符号组合"）：
#      ${数组[@]}     所有元素（最常用）
#      ${数组[*]}     所有元素（当成一整个字符串）
#      ${#数组[@]}    元素个数
#      ${!数组[@]}    所有下标
#      ${#数组[0]}    第 0 个元素的字符长度
# 4. 单个赋值：数组[下标]=值。下标已存在就是修改，
#    不存在就是新增。数组下标可以不连续，这叫"稀疏数组"。
# 5. 追加元素：数组+=(新元素)，注意是 += 而不是 =，否则会清空重建。
# 6. 遍历时一定要写 "${数组[@]}"（带双引号），
#    否则元素里的空格会被拆成两个元素。
# 7. 删除：unset '数组[下标]' 删一个元素，unset 数组 删掉整个数组。
# ------------------------------------------------------------

echo "===== 小节 1：定义数组与取值 ====="
fruits=("苹果" "香蕉" "橙子")          # 一次性定义三个元素
nums=(1 2 3 4 5)                       # 数字数组
echo "第 0 个元素：${fruits[0]}"        # 下标从 0 开始
echo "第 2 个元素：${fruits[2]}"
echo "全部元素：${fruits[@]}"           # ${数组[@]} 取出所有元素
echo "元素个数：${#fruits[@]}"          # ${#数组[@]} 是长度
echo "第 1 个元素的长度：${#fruits[1]}" # ${#数组[下标]} 是元素字符数
echo "数字数组全部：${nums[@]}"

echo
echo "===== 小节 2：修改、新增与追加 ====="
fruits[1]="西瓜"                       # 下标存在 -> 修改
fruits[3]="葡萄"                       # 下标不存在 -> 新增（变成 4 个）
fruits+=("芒果")                       # += 在末尾追加一个元素
echo "现在共 ${#fruits[@]} 个元素：${fruits[@]}"
echo "所有下标：${!fruits[@]}"          # ${!数组[@]} 列出全部下标

echo
echo "===== 小节 3：遍历数组 ====="
echo "-- 按值遍历（推荐写法） --"
for f in "${fruits[@]}"; do            # 双引号保证元素不被拆开
    echo "  元素：$f"
done
echo "-- 按下标遍历 --"
for i in "${!fruits[@]}"; do           # 先拿到所有下标
    echo "  下标 $i -> ${fruits[$i]}"   # 再用下标取值
done

echo
echo "===== 小节 4：带空格的元素 ====="
words=("hello world" "你好 世界" "ok")  # 前两个元素内部含空格
echo "元素个数：${#words[@]}"           # 正确写法：3 个
for w in "${words[@]}"; do             # 带引号遍历
    echo "  完整元素：[$w]"
done
echo "反面教材（不加引号会被拆开）："
for w in ${words[@]}; do               # 不加引号：空格处断成两个
    echo "  被拆成：[$w]"
done

echo
echo "===== 小节 5：删除元素 ====="
echo "删除前：${fruits[@]}"
unset 'fruits[0]'                      # 删除下标 0，一定要加引号
echo "删除下标 0 后：${fruits[@]}"
echo "剩余个数：${#fruits[@]}"          # 长度会自动变小
echo "取一个不存在的下标：${fruits[99]:-（空）}"

# ------------------------------------------------------------
