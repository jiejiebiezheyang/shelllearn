# 1 2 3 4 5
# 1 3 5 7 9
# a b c d e
#
# ===== 小节 3：seq 命令生成序列 =====
# seq 第 1 轮
# seq 第 2 轮
# seq 第 3 轮
# 10 8 6 4
#
# ===== 小节 4：C 风格 for =====
# C 风格第 1 轮
# C 风格第 2 轮
# C 风格第 3 轮
# 1 加到 100 的结果：5050
#
# ===== 小节 5：遍历命令输出与数组 =====
# 文件名：a.txt
# 文件名：b.txt
# 文件名：c.txt
# 姓名：张三
# 姓名：李四
# 姓名：王五
#
# ===== 小节 6：结合 continue 跳过 =====
# 奇数：1
# 奇数：3
# 奇数：5
