#!/bin/bash
# ============================================
# 序号: 07
# 主题: for 循环
# 难度: ★★☆
# 前置知识: 04 条件判断、06 数值比较
# 学习目标: 掌握 for 的列表、花括号范围、seq、C 风格四种写法
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. 最常用的形式：for 变量 in 值1 值2 值3; do ... done
#    变量会依次等于列表里的每一个值，每轮执行一次循环体。
# 2. "列表"可以是：
#      · 直接写的若干项：          in 苹果 香蕉 橙子
#      · 花括号范围：              in {1..5}、{a..e}、{1..10..2}
#      · 命令的输出：              in $(ls)、in $(seq 1 3)
#      · 数组的全部元素：          in "${数组[@]}"
#      · 位置参数：                in "$@"
# 3. seq 1 5 生成 1 到 5；seq 1 2 9 生成 1 3 5 7 9（步长 2）。
# 4. C 风格：for ((i=0; i<5; i++))，适合需要下标的场景，
#    它是 bash 扩展，写 sh 脚本时不能用。
# 5. in 后面的内容省略时，默认遍历位置参数 "$@"。
# 6. 循环里同样可以用 break 跳出、continue 跳过本轮（详见第 08 课）。
# ------------------------------------------------------------

echo "===== 小节 1：列表形式 ====="
for fruit in 苹果 香蕉 橙子; do       # in 后面直接列出来
    echo "我喜欢吃：$fruit"           # 每轮换一个值
done

echo
echo "===== 小节 2：花括号范围 ====="
for i in {1..5}; do                   # {1..5} 自动展开成 1 2 3 4 5
    echo -n "$i "                     # -n 表示不换行
done
echo                                  # 补一个换行
for i in {1..10..2}; do               # 第三个数字是步长，这里取奇数
    echo -n "$i "
done
echo
for c in {a..e}; do                   # 字母也能用范围
    echo -n "$c "
done
echo

echo
echo "===== 小节 3：seq 命令生成序列 ====="
for i in $(seq 1 3); do               # seq 1 3 输出 1 2 3
    echo "seq 第 $i 轮"
done
for i in $(seq 10 -2 4); do           # seq 起始 步长 结束
    echo -n "$i "
done
echo

echo
echo "===== 小节 4：C 风格 for ====="
for ((i = 1; i <= 3; i++)); do        # 初始化; 条件; 步进
    echo "C 风格第 $i 轮"
done
sum=0                                 # 用 C 风格 for 累加
for ((i = 1; i <= 100; i++)); do
    sum=$((sum + i))                  # 累加每一步的 i
done
echo "1 加到 100 的结果：$sum"

echo
echo "===== 小节 5：遍历命令输出与数组 ====="
for f in $(echo "a.txt b.txt c.txt"); do   # 遍历命令的输出
    echo "文件名：$f"
done
names=("张三" "李四" "王五")           # 定义数组（详见第 09 课）
for n in "${names[@]}"; do            # 遍历数组全部元素
    echo "姓名：$n"
done

echo
echo "===== 小节 6：结合 continue 跳过 ====="
for i in {1..6}; do
    if (( i % 2 == 0 )); then         # 偶数就跳过
        continue
    fi
    echo "奇数：$i"
done

# ------------------------------------------------------------
