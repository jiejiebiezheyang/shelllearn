#!/bin/bash
# ============================================
# 序号: 13
# 主题: 命令替换与算术运算
# 难度: ★★☆
# 前置知识: 01 变量定义与使用
# 学习目标: 掌握 $() 命令替换与 $(( ))、let、expr 三种算术写法
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. 命令替换：把一条命令的输出当成字符串取回来，两种写法：
#      today=$(date +%F)      # 推荐，可以嵌套
#      today=`date +%F`       # 老写法，反引号，嵌套时非常难读
#    命令替换会自动去掉末尾的换行符，行内的换行会保留。
# 2. 算术运算 $(( ))：bash 内置，速度最快，支持整数运算
#      + - * / %  加 减 乘 除 取余
#      ** 乘方       ++ -- 自增自减
#      括号可以随意嵌套
# 3. 重要限制：bash 只做整数运算！$((5/2)) 结果是 2（向下取整），
#    需要小数就交给 awk 或 bc。
# 4. let：let "sum=a+b"，直接把结果赋给变量，和 ((sum=a+b)) 等价。
# 5. expr：外部命令，写法最啰嗦，还要注意 * 必须转义，
#    如今主要用于兼容极老的 shell，新脚本不建议用。
# 6. 变量参与运算时不用写 $：( ( a + b ))，但写上也不算错。
# 7. 命令替换和算术运算可以嵌套：echo $(( $(date +%Y) - 2000 ))
# ------------------------------------------------------------

echo "===== 小节 1：命令替换 \$() ====="
today=$(date +%F)                    # 取当前日期，格式 2024-01-01
now=$(date +%H:%M:%S)                # 取当前时间
echo "今天是：$today"
echo "现在是：$now"
echo "当前目录：$(pwd)"               # 命令替换直接写在字符串里
echo "本机内核：$(uname -r)"
echo "文件总数：$(ls / | wc -l) 个（根目录下）"
echo "嵌套命令替换：$(echo "今天是 $(date +%Y) 年")"

echo
echo "===== 小节 2：反引号写法（了解即可） ====="
old_style=`date +%Y`                 # 反引号是老写法
echo "反引号取到的年份：$old_style"
echo "推荐还是写 \$( ) ，因为反引号无法方便地嵌套"

echo
echo "===== 小节 3：\$(( )) 算术运算 ====="
a=17                                 # 第一个操作数
b=5                                  # 第二个操作数
echo "a=$a  b=$b"
echo "加法 a + b   = $((a + b))"
echo "减法 a - b   = $((a - b))"
echo "乘法 a * b   = $((a * b))"
echo "除法 a / b   = $((a / b))   <-- 整数除法，小数被丢掉"
echo "取余 a % b   = $((a % b))"
echo "乘方 2 ** 10 = $((2 ** 10))"
echo "复杂表达式 (a + b) * 2 - 3 = $(((a + b) * 2 - 3))"
c=1
((c++))                              # 自增
echo "自增后 c = $c"
((c += 10))                          # 复合赋值
echo "c += 10 后 c = $c"

echo
echo "===== 小节 4：整数除法的坑与小数方案 ====="
echo "5 / 2 = $((5 / 2))   <-- 不是 2.5"
echo "小数用 awk：$(awk 'BEGIN{printf "%.2f", 10/3}')"
echo "小数用 awk 做四舍五入：$(awk 'BEGIN{printf "%.0f", 2.5 + 0.1}')"

echo
echo "===== 小节 5：let 与 expr ====="
x=3                                  # 参与运算的变量
y=4
let "sum = x + y"                    # let 直接把结果赋给 sum
echo "let 结果 sum = $sum"
let "x++"                            # let 也能自增
echo "let x++ 之后 x = $x"
echo "expr 写法：$(expr 3 + 4)"      # expr 是外部命令
echo "expr 乘法必须转义：$(expr 3 \* 4)"
echo "expr 也能算字符串长度：$(expr length "hello")"

echo
echo "===== 小节 6：命令替换 + 算术运算 ====="
year=$(date +%Y)                     # 先取年份
echo "今年是 $year 年"
echo "2000 年出生的人今年 $((year - 2000)) 岁"
echo "嵌套写法：$(( $(date +%Y) + 1 )) 年是明年"

# ------------------------------------------------------------
