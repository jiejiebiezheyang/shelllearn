# 现在是：12:00:00
# 当前目录：/home/你的用户名/code/sh
# 本机内核：6.x.x-generic（随机器不同）
# 文件总数：20 个（根目录下，随机器不同）
# 嵌套命令替换：今天是 2025 年
#
# ===== 小节 2：反引号写法（了解即可） =====
# 反引号取到的年份：2025
# 推荐还是写 $( ) ，因为反引号无法方便地嵌套
#
# ===== 小节 3：$(( )) 算术运算 =====
# a=17  b=5
# 加法 a + b   = 22
# 减法 a - b   = 12
# 乘法 a * b   = 85
# 除法 a / b   = 3   <-- 整数除法，小数被丢掉
# 取余 a % b   = 2
# 乘方 2 ** 10 = 1024
# 复杂表达式 (a + b) * 2 - 3 = 41
# 自增后 c = 2
# c += 10 后 c = 12
#
# ===== 小节 4：整数除法的坑与小数方案 =====
# 5 / 2 = 2   <-- 不是 2.5
# 小数用 awk：3.33
# 小数用 awk 做四舍五入：3
#
# ===== 小节 5：let 与 expr =====
