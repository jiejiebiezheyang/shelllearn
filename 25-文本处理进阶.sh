# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. awk 的固定句式：awk '模式 {动作}' 文件
#    省略模式 = 每一行都执行；省略动作 = 打印整行。
# 2. 字段与内置变量（默认按空格/Tab 分列，可用 -F 改分隔符）：
#      $1 $2 …  第 n 列          $0  整行
#      $NF      最后一列          $(NF-1) 倒数第二列
#      NR       当前行号（总共处理了多少行）
#      NF       当前行的列数       FS  字段分隔符
# 3. -F 指定分隔符：awk -F, '{print $1}' 按逗号分列；
#    分隔符是正则时也照收，例如 -F'[,;]' 表示逗号或分号。
# 4. BEGIN 和 END 两个特殊块：
#      BEGIN { 动作 }  读取文件之前执行一次（常用来打印表头、初始化）
#      END   { 动作 }  全部行处理完后执行一次（常用来输出合计、平均）
# 5. printf 格式化：printf "%-6s %3d\n", $1, $2
#      %s 字符串  %d 整数  %f 小数  %-6s 左对齐占 6 格  %3d 右对齐占 3 格
# 6. sed 替换的分组与反向引用：
#      sed -E 's/([0-9]+)/[\1]/'     用括号分组，\1 引用第 1 组
#      sed -E 's/(a)(b)/\2\1/'       交换两组的位置
# 7. sed 其他常用参数：-n 'Np' 只打印第 N 行；-e 连接多条编辑命令；
#      -i 原地改文件（危险操作，先用不带 -i 的预览一遍）；'/模式/d' 删行。
# ------------------------------------------------------------

datafile=$(mktemp)                     # 自建测试数据（CSV 格式）
cat > "$datafile" <<'EOF'
张三,语文,85
李四,数学,92
王五,英语,78
赵六,数学,88
EOF

echo "===== 小节 1：awk 取列（-F 指定分隔符） ====="
echo "-- 原始数据 --"
cat "$datafile"
echo "-- 只取第 1 列和第 3 列 --"
awk -F, '{print $1, $3}' "$datafile"
echo "-- 用分隔符重新拼回去 --"
awk -F, '{print $1 " 的 " $2 " 成绩是 " $3 " 分"}' "$datafile"

echo
echo "===== 小节 2：awk 内置变量 NR NF \$NF ====="
awk -F, '{print "第" NR "行，共" NF "列，最后一列是：" $NF}' "$datafile"
awk -F, 'END {print "总行数 NR = " NR}' "$datafile"

echo
echo "===== 小节 3：awk 条件过滤与统计 ====="
echo "-- 分数大于等于 85 的 --"
awk -F, '$3 >= 85 {print $1 " -> " $3 " 分，优秀"}' "$datafile"
echo "-- 科目是数学的 --"
awk -F, '$2 == "数学" {print $1, $3}' "$datafile"
echo "-- 求和与平均（END 里算） --"
awk -F, '{sum += $3} END {print "总分：" sum "，平均分：" sum / NR}' "$datafile"

echo
echo "===== 小节 4：awk 的 BEGIN / END 与格式化输出 ====="
echo "（小提示：%-6s 这类宽度对中文不友好，它按字节算宽度，"
echo "  一个汉字占 3 字节，对不齐，所以下面用 | 做分隔更清楚）"
awk -F, 'BEGIN {print "===== 成绩单 ====="}
         {printf "%s | %s | %3d 分\n", $1, $2, $3}
         END {print "===== 共 " NR " 条记录 ====="}' "$datafile"

echo
echo "===== 小节 5：sed 替换与反向引用 ====="
echo "-- 每行行首加两个空格 --"
sed 's/^/  /' "$datafile"
echo "-- 逗号换成短横线（全部替换要加 g） --"
sed 's/,/-/g' "$datafile"
echo "-- 用分组把分数包上中括号（\\1 引用第一个括号的内容） --"
sed -E 's/([0-9]+)$/[\1]/' "$datafile"
echo "-- 交换姓名和科目的位置 --"
sed -E 's/^([^,]+),([^,]+)/\2,\1/' "$datafile"

echo
echo "===== 小节 6：sed 打印与删除指定行 ====="
echo "-- 只打印第 2 到第 3 行（-n 取消默认输出） --"
sed -n '2,3p' "$datafile"
echo "-- 只打印最后一行（\$ 表示最后一行） --"
sed -n '$p' "$datafile"
echo "-- 删除所有含数学的行 --"
sed '/数学/d' "$datafile"

echo
echo "===== 小节 7：sed -i 原地修改文件 ====="
copyfile="$datafile.copy"              # 用副本演示，不破坏原始数据
cp "$datafile" "$copyfile"
echo "修改前：$(head -1 "$copyfile")"
sed -i 's/,/ | /g' "$copyfile"         # -i 直接改写文件本身
echo "修改后：$(head -1 "$copyfile")"
echo "（-i 会真的改动文件，实操时先用不带 -i 的命令预览一遍更稳妥）"
rm -f "$copyfile"

echo
echo "===== 小节 8：awk + sed 组合统计 ====="
echo "-- 数学平均分 --"
awk -F, '/数学/ {sum += $3; n++} END {printf "数学平均分：%.1f\n", sum / n}' "$datafile"
echo "-- 把结果整理成整齐的报表（管道组合） --"
awk -F, '{printf "%s | %s | %3d\n", $1, $2, $3}' "$datafile" | sed 's/^/  /'

rm -f "$datafile"                      # 清理临时数据
echo
echo "临时数据文件已清理"

