# ------------------------------------------------------------
# 【知识点讲解】
# 1. case 适合"一个值对多种可能"的场景，比一长串 if/elif 清爽得多。
#    语法：
#      case "$变量" in
#          模式1) 命令 ;;      # ;; 表示这个分支结束
#          模式2|模式3) 命令 ;; # 用 | 表示"或"
#          *) 兜底命令 ;;      # * 匹配剩下的一切，放最后
#      esac                     # esac 就是 case 倒过来写
# 2. case 的模式支持 shell 通配符：
#      *     任意多个字符        ?     任意一个字符
#      [a-z] 范围内的一个字符    [0-9] 一个数字
#      *.txt 按后缀匹配文件名    st*   以 st 开头
# 3. 每个分支最后的 ;; 不能忘（忘了一般会报语法错误）。
# 4. 兜底分支 *) 建议必写，否则没有匹配时脚本会静默什么都不做。
# 5. case 的匹配是"从上往下、命中即停"，所以范围小的模式要写在前面，
#    * 这种大范围模式必须放在最后一个。
# 6. case 也能匹配空字符串：写 "" ) ... ;; 即可。
# ------------------------------------------------------------

echo "===== 小节 1：case 的基本写法 ====="
fruit="apple"                          # 要判断的值
case "$fruit" in                       # case 后面跟变量（加引号更安全）
    apple)                             # 模式) 开启一个分支
        echo "苹果：5 元/斤"           # 命中后执行的命令
        ;;                             # ;; 结束本分支
    banana)
        echo "香蕉：3 元/斤"
        ;;
    *)                                 # 兜底分支
        echo "未知水果"
        ;;
esac                                   # esac 结束整个 case

echo
echo "===== 小节 2：多模式与通配符 ====="
for input in start stop restart status foo; do   # 逐个命令依次判断
    case "$input" in
        start|begin)                   # 用 | 表示 start 或 begin
            echo "[$input] -> 启动服务"
            ;;
        stop|end)                      # 多个别名归到同一个分支
            echo "[$input] -> 停止服务"
            ;;
        restart)
            echo "[$input] -> 重启服务"
            ;;
        st*)                           # st 开头的一律按状态查询处理
            echo "[$input] -> 以 st 开头，按状态查询处理"
            ;;
        *)                             # 谁都不匹配时走这里
            echo "[$input] -> 无法识别的命令"
            ;;
    esac
done

echo
echo "===== 小节 3：按文件名后缀分类 ====="
for f in photo.jpg music.mp3 note.txt data.csv; do
    case "$f" in
        *.jpg|*.png)                   # 通配符按后缀匹配
            echo "$f -> 图片文件"
            ;;
        *.mp3)
            echo "$f -> 音频文件"
            ;;
        *.txt|*.md)
            echo "$f -> 文本文件"
            ;;
        *)
            echo "$f -> 其他文件"
            ;;
    esac
done

echo
echo "===== 小节 4：字符范围匹配 ====="
for ch in a G 7; do                    # 三种不同类型的单字符
    case "$ch" in
        [a-z]) echo "$ch -> 小写字母" ;;   # 一个分支也能写成一行
        [A-Z]) echo "$ch -> 大写字母" ;;
        [0-9]) echo "$ch -> 数字" ;;
        *)     echo "$ch -> 其他字符" ;;
    esac
done

echo
echo "===== 小节 5：匹配空字符串 ====="
empty=""                               # 空字符串也能作为模式
case "$empty" in
    "")   echo "命中了空字符串分支" ;;
    *)    echo "命中了其他分支" ;;
esac

# ------------------------------------------------------------
