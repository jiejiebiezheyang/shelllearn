#!/bin/bash
# ============================================
# 序号: 11
# 主题: 输入输出重定向
# 难度: ★★☆
# 前置知识: 01 变量定义与使用
# 学习目标: 掌握 >、>>、<、2>、2>&1、/dev/null 与 here-document
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. Linux 里每个程序天生有三个"通道"（文件描述符）：
#      0 标准输入(stdin)   1 标准输出(stdout)   2 标准错误(stderr)
#    正常信息走 1，报错信息走 2，所以它们能分别改道。
# 2. 输出重定向：
#      >  覆盖写入（文件原有内容会被清空！）
#      >> 追加写入（保留原内容，写在末尾）
# 3. 输入重定向：命令 < 文件，把文件内容当成这个命令的键盘输入。
#    例如 wc -l < a.txt 就不需要再写文件名参数了。
# 4. 错误重定向：2> 文件 只把错误信息写进文件；
#    2>&1 表示"把错误输出并到标准输出去"，&1 指的是"1 号通道"。
#    顺序很关键：> all.txt 2>&1 才是"全都要"，
#    写成 2>&1 > all.txt 则错误仍然打在屏幕上。
# 5. /dev/null 是"黑洞文件"，写进去的东西直接消失，常用于屏蔽输出。
# 6. here-document（<<EOF ... EOF）能把一段文本直接喂给命令，
#    给 EOF 加引号（<<'EOF'）可以阻止里面的 $变量 被展开。
# 7. 本脚本用 mktemp -d 自建临时目录，结束时删除，不污染你的电脑。
# ------------------------------------------------------------

workdir=$(mktemp -d)                 # 创建临时目录，脚本自带"实验场地"
cd "$workdir" || exit 1              # 进入临时目录，失败就退出
echo "临时工作目录：$workdir"

echo
echo "===== 小节 1：输出重定向 > 与 >> ====="
echo "第一行" > out.txt              # > 覆盖写入，文件不存在会自动创建
echo "第二行" >> out.txt             # >> 追加写入，不清空原有内容
echo "第三行" >> out.txt             # 再追加一行
echo "现在 out.txt 有 $(wc -l < out.txt) 行："
cat out.txt                          # 查看文件内容

echo
echo "===== 小节 2：输入重定向 < ====="
wc -l < out.txt                      # 把文件当输入喂给 wc，不用写文件名
read -r first_line < out.txt         # 只读进第一行
echo "用 read 读到的第一行：$first_line"

echo
echo "===== 小节 3：错误重定向 2> ====="
ls /这个目录不存在 2> err.txt        # 2> 只把错误信息收进文件
echo "错误信息已经写进 err.txt，内容是："
cat err.txt
ls /这个目录不存在 > /dev/null 2>&1  # 正确和错误输出全部丢进黑洞
echo "上一行命令什么都没显示，因为输出都被丢进 /dev/null 了"

echo
echo "===== 小节 4：合并输出 > all.txt 2>&1 ====="
{ echo "这是正常输出"; ls /这个目录不存在; } > all.txt 2>&1   # 两类输出都进同一个文件
echo "all.txt 共 $(wc -l < all.txt) 行，内容如下："
cat all.txt

echo
echo "===== 小节 5：here-document ====="
cat <<EOF > note.txt                 # 两个 EOF 之间的内容写进 note.txt
姓名：小明
年龄：18
EOF
echo "note.txt 的内容："
cat note.txt
cat <<'EOF'                          # 引号包住的 EOF：内部变量不会被替换
单引号模式：$HOME 原样输出，不会被展开
EOF
cat <<EOF
普通模式：当前用户家目录是 $HOME
EOF

echo
echo "===== 小节 6：清空文件的小技巧 ====="
echo "一些内容" > empty_me.txt      # 先写入内容
: > empty_me.txt                     # 用 : 命令 + > 把文件清空
echo "清空后 empty_me.txt 的字节数：$(wc -c < empty_me.txt)"

cd / && rm -rf "$workdir"            # 先离开再删除临时目录，保持环境干净
echo "临时目录已清理"

# ------------------------------------------------------------
# 运行结果（临时目录名每次不同）：
# 临时工作目录：/tmp/tmp.xxxxxxxx
#
# ===== 小节 1：输出重定向 > 与 >> =====
# 现在 out.txt 有 3 行：
# 第一行
# 第二行
# 第三行
#
# ===== 小节 2：输入重定向 < =====
# 3
# 用 read 读到的第一行：第一行
#
# ===== 小节 3：错误重定向 2> =====
# 错误信息已经写进 err.txt，内容是：
# ls: cannot access '/这个目录不存在': No such file or directory
# 上一行命令什么都没显示，因为输出都被丢进 /dev/null 了
#
# ===== 小节 4：合并输出 > all.txt 2>&1 =====
# all.txt 共 2 行，内容如下：
# 这是正常输出
# ls: cannot access '/这个目录不存在': No such file or directory
#
# ===== 小节 5：here-document =====
# note.txt 的内容：
# 姓名：小明
# 年龄：18
# 单引号模式：$HOME 原样输出，不会被展开
# 普通模式：当前用户家目录是 /home/你的用户名
#
# ===== 小节 6：清空文件的小技巧 =====
# 清空后 empty_me.txt 的字节数：0
# 临时目录已清理
# ------------------------------------------------------------
