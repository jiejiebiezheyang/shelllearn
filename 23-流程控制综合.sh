# 2) 重启服务
# 3) 查看日志
# 4) 退出
# 请选择操作(1-4)：   -> 系统状态正常，负载 0.15
# 请选择操作(1-4)：   -> 再见！
# （用管道喂输入时，菜单只在开头打印一次；在终端里手动操作时每轮都会重印菜单）
#
# ===== 小节 2：嵌套循环打印乘法表 =====
# 1*1=1  1*2=2  1*3=3  
# 2*1=2  2*2=4  2*3=6  
# 3*1=3  3*2=6  3*3=9  
#
# ===== 小节 3：嵌套 + break 2 提前跳出 =====
#   i=1 j=1 乘积=1
#   i=1 j=2 乘积=2
#   i=1 j=3 乘积=3
#   i=2 j=1 乘积=2
#   i=2 j=2 乘积=4
#   i=2 j=3 乘积超过 4，跳出全部循环
#
# ===== 小节 4：状态机（while + case） =====
#   第 1 步：初始化完成 -> running
#   第 2 步：任务执行中 -> checking
#   第 3 步：检查通过 -> done
# 状态机结束，共走了 3 步
#
