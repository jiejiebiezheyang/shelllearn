# 前置知识: 07 for 循环、08 while 循环、10 函数定义与返回值
# 学习目标: 掌握嵌套循环、select 菜单、状态机与循环和函数的配合
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. 嵌套循环：循环里再写循环，外层走一步、内层走一整圈。
#    打印乘法表、二维表格都是这个套路。注意 break n 可以一次跳出 n 层。
# 2. select 是 bash 的"菜单生成器"，写法：
#      select 变量 in 选项1 选项2 选项3; do ... done
#    它会自动编号、自动循环，把用户选中的那个"选项文本"赋给变量。
#    用户输入的数字对应第几项，变量就等于第几项的文本。
# 3. select 的几个要点：
#      · 菜单和提示符（PS3，默认 "#? "）打印到 stderr；
#      · 输入无效编号时变量为空，需要在 case 里用 *) 兜底；
#      · 必须自己写 break 才能退出，否则会一直循环；
#      · 它能从管道/重定向读输入，本脚本就用 printf 喂它，
#        这样不用人工敲键盘也能演示。
# 4. PS3 变量可以改提示符，例如 PS3="请选择> "。
# 5. 状态机套路：用一个变量记录"当前状态"，while + case 反复推进，
#    每个分支负责把状态改成下一个值，直到变成终止状态。
# 6. 函数 + 循环配合：函数里用 return 提前结束查找，
#    调用方用 if 函数名; then 判断有没有找到。
# ------------------------------------------------------------

echo "===== 小节 1：select 菜单 ====="
echo "下面用 printf 喂入两个选择（先选 1，再选 4 退出）来模拟操作："
printf '1\n4\n' | {
    PS3="请选择操作(1-4)： "            # PS3 是 select 的提示符
    select opt in "查看状态" "重启服务" "查看日志" "退出"; do
        case "$opt" in
            "查看状态") echo "  -> 系统状态正常，负载 0.15" ;;
            "重启服务") echo "  -> 服务已重启完毕" ;;
            "查看日志") echo "  -> 最近 10 行日志已打印" ;;
            "退出")     echo "  -> 再见！"; break ;;   # 必须 break 才退出
            *)          echo "  -> 无效选择，请输入 1-4 的数字" ;;
        esac
    done
}

echo
echo "===== 小节 2：嵌套循环打印乘法表 ====="
for i in 1 2 3; do                     # 外层控制行
    for j in 1 2 3; do                 # 内层控制列
        printf "%d*%d=%-3d" "$i" "$j" $((i * j))   # %-3d 左对齐占 3 格
    done
    echo                               # 一行结束换行
done

echo
echo "===== 小节 3：嵌套 + break 2 提前跳出 ====="
for i in 1 2 3; do
    for j in 1 2 3; do
        if (( i * j > 4 )); then       # 一旦乘积超过 4
            echo "  i=$i j=$j 乘积超过 4，跳出全部循环"
            break 2                    # 一次跳出两层
        fi
        echo "  i=$i j=$j 乘积=$((i * j))"
    done
done

echo
echo "===== 小节 4：状态机（while + case） ====="
state="start"                          # 当前状态
step=0                                 # 步数，兼作保险丝
while [[ "$state" != "done" ]]; do
    step=$((step + 1))
    case "$state" in
        start)    echo "  第 $step 步：初始化完成 -> running";  state="running" ;;
        running)  echo "  第 $step 步：任务执行中 -> checking";  state="checking" ;;
        checking) echo "  第 $step 步：检查通过 -> done";        state="done" ;;
        *)        echo "  第 $step 步：未知状态，强制结束";      state="done" ;;
    esac
    if (( step > 20 )); then           # 防止死循环的保险丝
        echo "  步数异常，强制退出"
        break
    fi
done
echo "状态机结束，共走了 $step 步"

echo
echo "===== 小节 5：函数 return 与循环配合 ====="
find_first_even() {                    # 找出第一个偶数
    local n
    for n in "$@"; do                  # 遍历所有参数
        if (( n % 2 == 0 )); then
            echo "$n"                  # 用 echo 把值送出去
            return 0                   # 找到就用 return 0 结束函数
        fi
    done
    return 1                           # 找遍了也没有
}
if result=$(find_first_even 3 5 8 9 12); then
    echo "  3 5 8 9 12 中第一个偶数是：$result"
else
    echo "  没有找到偶数"
fi
if find_first_even 1 3 5 > /dev/null; then
    echo "  1 3 5 中有偶数"
else
    echo "  1 3 5 中没有偶数"
fi

echo
echo "===== 小节 6：综合小案例 —— 简易成绩报表 ====="
students=("张三:85" "李四:92" "王五:58" "赵六:76")   # 数据形如 姓名:分数
print_report() {                       # 打印报表的函数
    local item name score level
    for item in "${students[@]}"; do
        name="${item%%:*}"             # 冒号左边是姓名
        score="${item##*:}"            # 冒号右边是分数
        if (( score >= 90 )); then level="优秀"
        elif (( score >= 60 )); then level="合格"
        else level="不及格"; fi
        printf "  %s  %3d 分  %s\n" "$name" "$score" "$level"   # %3d 让分数右对齐
    done
}
print_report

# ------------------------------------------------------------
