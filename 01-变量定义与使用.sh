# ------------------------------------------------------------
# 【知识点讲解】
# 1. 定义变量：变量名=值。等号两边绝对不能有空格！
#      name="小明"    正确
#      name = "小明"  错误（bash 会把 name 当成一条命令去执行）
# 2. 使用变量：$变量名 或 ${变量名}。推荐加花括号，
#    例如 "${name}同学"，否则 bash 会去找名为 name同学 的变量。
# 3. 三种常见定义方式：
#    · 普通变量：只有当前这个 shell 自己能看到。
#    · readonly 只读变量：赋值后不能再改、也不能 unset。
#    · export 环境变量：子进程（子 shell、其他命令）也能读到。
# 4. 变量名规则：只能由字母、数字、下划线组成，不能以数字开头，
#    区分大小写；习惯上环境变量用全大写，如 PATH、HOME。
# 5. 作用域：父 shell 的普通变量不会传给子 shell，export 之后才会；
#    反过来，子 shell 里改环境变量也影响不到父 shell。
# 6. 删除变量用 unset 变量名，但 readonly 变量删不掉。
# ------------------------------------------------------------

echo "===== 小节 1：普通变量 ====="
name="小明"                    # 定义普通变量，等号两边不能有空格
age=18                         # 数字也直接赋值（本质仍是字符串）
echo "姓名: $name"             # 用 $变量名 取值
echo "年龄: ${age}岁"          # 用 ${变量名} 取值，避免和后面的字粘在一起
echo "姓名长度: ${#name}"      # ${#变量} 取出字符串长度
unset age                      # 删除变量 age
echo "删除后 age = [${age}]"   # 删除后取值为空，不会报错

echo
echo "===== 小节 2：readonly 只读变量 ====="
readonly pi=3.14               # 定义只读变量，之后不允许修改
echo "pi = $pi"                # 正常读取没问题
# pi=3.15                      # 取消注释会报错：readonly variable
# unset pi                     # 取消注释也会报错：cannot unset
echo "尝试修改只读变量会被 bash 拒绝（见代码注释）"

echo
echo "===== 小节 3：export 环境变量与作用域 ====="
export MY_ENV="我是环境变量"    # export 之后，子进程也能看到
LOCAL_VAR="我是普通变量"        # 没有 export，子进程看不到
echo "父 shell 中 MY_ENV    = $MY_ENV"
echo "父 shell 中 LOCAL_VAR = $LOCAL_VAR"
echo "--- 进入子 shell 查看 ---"
bash -c 'echo "子 shell 中 MY_ENV    = ${MY_ENV:-（读不到）}"'    # 能读到
bash -c 'echo "子 shell 中 LOCAL_VAR = ${LOCAL_VAR:-（读不到）}"'  # 读不到

