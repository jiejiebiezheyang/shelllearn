#!/bin/bash
# ============================================
# 序号: 15
# 主题: 字符串处理进阶（${var#} ${var%} 模式匹配）
# 难度: ★★★
# 前置知识: 03 字符串操作
# 学习目标: 掌握 ${var#} ${var##} ${var%} ${var%%} 四类模式裁剪
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. 记忆口诀：# 在键盘左边，管"开头"；% 在键盘右边，管"结尾"。
#      一个 # 或 % = 最短匹配（删得少）
#      两个 ## 或 %% = 最长匹配（删得多）
# 2. 四种裁剪（都是"删除"的含义，返回删完剩下的部分，原变量不变）：
#      ${var#模式}    从头删掉最短匹配
#      ${var##模式}   从头删掉最长匹配
#      ${var%模式}    从尾删掉最短匹配
#      ${var%%模式}   从尾删掉最长匹配
# 3. 模式里可以使用通配符 * 和 ?，这也是它比"按位置截取"强大的地方：
#    不需要知道文件名多长，就能一刀切掉路径或后缀。
# 4. 最经典的三个实战用法：
#      ${path##*/}    取文件名（等价于 basename）
#      ${path%/*}     取目录名（等价于 dirname）
#      ${file%.*}     去掉最后一个后缀
#      ${file##*.}    只取扩展名
# 5. 要替换而不是删除，用第 03 课的 ${var/旧/新} 和 ${var//旧/新}。
# 6. 提示：模式要加引号防止被 shell 提前展开，一般写成 "${path##*/}"。
# ------------------------------------------------------------

echo "===== 小节 1：# 与 ## 从头删除 ====="
path="/home/user/docs/report.tar.gz"     # 一个多级路径
echo "原字符串            : $path"
echo "\${path#*/}  最短删到第一个 / : ${path#*/}"
echo "\${path##*/} 最长删到最后一个 / : ${path##*/}"
echo "记忆：## 贪心，删得最多，所以剩下的是文件名"

echo
echo "===== 小节 2：% 与 %% 从尾删除 ====="
file="report.tar.gz"                     # 一个多后缀文件名
echo "原字符串            : $file"
echo "\${file%.*}  最短删后缀 : ${file%.*}"
echo "\${file%%.*} 最长删后缀 : ${file%%.*}"
echo "记忆：%% 贪心，从右边一路吃到最左边的点"

echo
echo "===== 小节 3：通配符模式裁剪 ====="
name="2024-01-15_日志备份.txt"            # 带日期前缀的文件名
echo "原字符串              : $name"
echo "删掉日期前缀（*-）      : ${name#*-}"
echo "删掉日期前缀（*-*-）    : ${name#*-*-}"
echo "删掉最后的下划线后缀    : ${name%_*}"
echo "只保留日期部分          : ${name%%_*}"

echo
echo "===== 小节 4：经典组合用法 ====="
full="/var/log/nginx/access.log"          # 拿一个真实感强一点的路径
echo "完整路径      : $full"
echo "文件名        : ${full##*/}   （等价于 basename）"
echo "所在目录      : ${full%/*}    （等价于 dirname）"
echo "扩展名        : ${full##*.}"
echo "去掉扩展名    : ${full%.*}"
url="https://example.com/api/v1/users"    # 用同样思路拆 URL
echo "URL 协议部分  : ${url%%:*}"
echo "URL 域名部分  : ${url#*//}"

echo
echo "===== 小节 5：批量处理文件名 ====="
files=("photo.jpg" "music.mp3" "note.txt" "archive.tar.gz")   # 一组文件
for f in "${files[@]}"; do                # 逐个处理
    base="${f%.*}"                        # 去掉最后一个后缀
    ext="${f##*.}"                        # 取最后一个后缀
    echo "文件 $f -> 名称=[$base] 类型=[$ext]"
done

echo
echo "===== 小节 6：与按位置截取对比 ====="
s="abcdefg"                               # 短字符串便于对照
echo "按位置截取 \${s:2:3} = ${s:2:3}   （必须知道下标的数字）"
echo "按模式裁剪 \${s#ab}  = ${s#ab}    （只关心模式，不用数下标）"
echo "原变量始终没变：s = $s"

# ------------------------------------------------------------
# 运行结果：
# ===== 小节 1：# 与 ## 从头删除 =====
# 原字符串            : /home/user/docs/report.tar.gz
# ${path#*/}  最短删到第一个 / : home/user/docs/report.tar.gz
# ${path##*/} 最长删到最后一个 / : report.tar.gz
# 记忆：## 贪心，删得最多，所以剩下的是文件名
#
# ===== 小节 2：% 与 %% 从尾删除 =====
# 原字符串            : report.tar.gz
# ${file%.*}  最短删后缀 : report.tar
# ${file%%.*} 最长删后缀 : report
# 记忆：%% 贪心，从右边一路吃到最左边的点
#
# ===== 小节 3：通配符模式裁剪 =====
# 原字符串              : 2024-01-15_日志备份.txt
# 删掉日期前缀（*-）      : 01-15_日志备份.txt
# 删掉日期前缀（*-*-）    : 15_日志备份.txt
# 删掉最后的下划线后缀    : 2024-01-15
# 只保留日期部分          : 2024-01-15
#
# ===== 小节 4：经典组合用法 =====
# 完整路径      : /var/log/nginx/access.log
# 文件名        : access.log   （等价于 basename）
# 所在目录      : /var/log/nginx    （等价于 dirname）
# 扩展名        : log
# 去掉扩展名    : /var/log/nginx/access
# URL 协议部分  : https
# URL 域名部分  : example.com/api/v1/users
#
# ===== 小节 5：批量处理文件名 =====
# 文件 photo.jpg -> 名称=[photo] 类型=[jpg]
# 文件 music.mp3 -> 名称=[music] 类型=[mp3]
# 文件 note.txt -> 名称=[note] 类型=[txt]
# 文件 archive.tar.gz -> 名称=[archive.tar] 类型=[gz]
#
# ===== 小节 6：与按位置截取对比 =====
# 按位置截取 ${s:2:3} = cde   （必须知道下标的数字）
# 按模式裁剪 ${s#ab}  = cdefg    （只关心模式，不用数下标）
# 原变量始终没变：s = abcdefg
