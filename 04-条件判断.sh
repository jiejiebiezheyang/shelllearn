#!/bin/bash
# ============================================
# 序号: 04
# 主题: 条件判断 if / test / [ ] / [[ ]]
# 难度: ★★☆
# 前置知识: 01 变量定义与使用
# 学习目标: 掌握 if 语法结构与 test、[ ]、[[ ]] 三种判断写法的区别
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. if 的基本骨架：
#      if 条件; then ...; elif 条件; then ...; else ...; fi
#    then 可以写在下一行，也可以跟在 ; 后面。
# 2. test 和 [ ] 是同一个东西：[ 其实是一条命令，
#    所以 ] 前面、[ 后面都必须有空格，变量最好加双引号。
# 3. [[ ]] 是 bash 的增强版判断：
#    · 不会做单词拆分，变量不加引号也安全；
#    · 右侧不加引号时 * 是通配符，可以写 [[ $f == *.txt ]]；
#    · 支持 =~ 正则匹配，支持 && || 直接写在里面。
# 4. 常用判断：
#    · 字符串：= 相等、!= 不等、-z 为空、-n 非空
#    · 文件：-f 是文件、-d 是目录、-r/-w/-x 可读/可写/可执行
#    · 数值：-eq -ne -gt -lt -ge -le（数值比较详见第 06 课）
# 5. 退出码 0 表示"真"，非 0 表示"假"；if 判断的就是退出码。
# 6. 结论：写 bash 脚本时优先用 [[ ]]，只有需要兼容 sh 时才用 [ ]。
# ------------------------------------------------------------

echo "===== 小节 1：if / else 基本结构 ====="
score=85                                     # 准备一个分数
if [ "$score" -ge 60 ]; then                 # [ ] 本质是 test 命令，空格不能省
    echo "成绩 $score：及格"                 # 条件成立走这里
else
    echo "成绩 $score：不及格"               # 条件不成立走这里
fi                                           # fi 结束整个 if

echo
echo "===== 小节 2：test 与 [ ] 判断字符串 ====="
name=""                                      # 故意留空
if [ -z "$name" ]; then                      # -z 判断长度为 0
    echo "-z 判断：name 是空字符串"
fi
if [ -n "abc" ]; then                        # -n 判断长度不为 0
    echo "-n 判断：abc 不是空字符串"
fi
if test "a" = "a"; then                      # test 是最原始的写法，最直观
    echo "test 判断：两个字符串相等"
fi
if [ "a" != "b" ]; then                      # != 判断不相等
    echo "[ ] 判断：a 和 b 不相等"
fi

echo
echo "===== 小节 3：[[ ]] 的增强能力 ====="
file="report.txt"                            # 准备一个文件名
if [[ $file == *.txt ]]; then                # 右边不加引号，* 当通配符用
    echo "[[ ]] 通配符：$file 是 txt 文件"
fi
if [[ "hello world" == *"world"* ]]; then    # 用 *...* 判断是否包含子串
    echo "[[ ]] 子串：包含 world"
fi
if [[ "abc123" =~ ^[a-z]+[0-9]+$ ]]; then    # =~ 后面写正则表达式
    echo "[[ ]] 正则：abc123 符合 字母+数字"
fi
if [[ 1 -eq 1 && 2 -gt 1 ]]; then            # [[ ]] 里可直接用 && 和 ||
    echo "[[ ]] 逻辑：两个条件同时成立"
fi

echo
echo "===== 小节 4：文件判断 ====="
if [[ -f "$0" ]]; then                       # -f 判断是不是普通文件
    echo "-f 判断：$0 是一个存在的普通文件"
fi
if [[ -d /tmp ]]; then                       # -d 判断是不是目录
    echo "-d 判断：/tmp 是一个目录"
fi
if [[ ! -d /这个目录不存在 ]]; then           # ! 取反
    echo "! -d 判断：/这个目录不存在 确实不是目录"
fi

echo
echo "===== 小节 5：if / elif / else 多分支 ====="
for n in 95 75 40; do                        # 用三个分数轮番演示
    if [ "$n" -ge 90 ]; then                 # 从上往下依次判断
        echo "$n 分 -> 优秀"
    elif [ "$n" -ge 60 ]; then               # elif 可以有任意多个
        echo "$n 分 -> 合格"
    else                                     # 前面都不满足才走 else
        echo "$n 分 -> 待努力"
    fi
done

# ------------------------------------------------------------
