# -z 判断：name 是空字符串
# -n 判断：abc 不是空字符串
# test 判断：两个字符串相等
# [ ] 判断：a 和 b 不相等
#
# ===== 小节 3：[[ ]] 的增强能力 =====
# [[ ]] 通配符：report.txt 是 txt 文件
# [[ ]] 子串：包含 world
# [[ ]] 正则：abc123 符合 字母+数字
# [[ ]] 逻辑：两个条件同时成立
#
# ===== 小节 4：文件判断 =====
# -f 判断：04-条件判断.sh 是一个存在的普通文件
# -d 判断：/tmp 是一个目录
# ! -d 判断：/这个目录不存在 确实不是目录
#
# ===== 小节 5：if / elif / else 多分支 =====
# 95 分 -> 优秀
# 75 分 -> 合格
# 40 分 -> 待努力
