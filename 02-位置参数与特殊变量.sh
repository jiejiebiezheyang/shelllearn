#!/bin/bash
# ============================================
# 序号: 02
# 主题: 位置参数与特殊变量
# 难度: ★☆☆
# 前置知识: 01 变量定义与使用
# 学习目标: 掌握 $0 $1 $# $? $$ $@ 等特殊变量的含义与用法
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. 位置参数：运行脚本时跟在后面的参数，用 $1 $2 $3 … 依次取，
#    $0 表示脚本本身的名字。第 10 个起必须写 ${10}（不能写 $10）。
# 2. $# 是位置参数的个数；$@ 和 $* 是"所有参数"，不带引号时几乎一样。
# 3. 带引号时差别很大："$@" 展开成多个独立单词，"$*" 展开成一个整体，
#    所以遍历参数一律推荐用 "$@"。
# 4. $? 是上一条命令的退出码：0 表示成功，非 0 表示失败。
#    注意它随时会被下一条命令覆盖，要用就得马上用。
# 5. $$ 是当前 shell 的进程号（PID）；$! 是最近一个后台进程的 PID。
# 6. 取不存在的参数不会报错，只会得到空串；用 ${1:-默认值} 可以兜底。
# 7. shift 把参数整体左移一位（$1 被丢掉，$2 变成 $1），
#    常用于 while 循环里一个一个消费参数。
# ------------------------------------------------------------

# 为了演示方便：如果运行时没传参数，就用 set -- 补上几个示例参数
if [ $# -eq 0 ]; then
    set -- 苹果 香蕉 "带 空格 的参数"    # set -- 用来重新设置位置参数
fi

echo "===== 小节 1：\$0 与位置参数 \$1 \$2 ====="
echo "脚本名 \$0      = $0"                      # $0 就是脚本文件本身
echo "第 1 个参数 \$1 = $1"                      # 取第 1 个位置参数
echo "第 2 个参数 \$2 = $2"                      # 取第 2 个位置参数
echo "第 3 个参数 \$3 = ${3:-（没传，用默认值）}"   # :- 提供默认值
echo "第 10 个参数 \${10} = ${10:-（没传）}"       # 两位数必须加花括号

echo
echo "===== 小节 2：\$# \$@ \$* 与遍历 ====="
echo "参数个数 \$# = $#"                        # 统计参数个数
echo "所有参数 \$* = [$*]"                      # $* 把所有参数当成一坨
i=1
for arg in "$@"; do                             # "$@" 保留每个参数的边界
    echo "  第 $i 个参数：[$arg]"               # 带空格的参数也不会被拆开
    i=$((i + 1))                                # 计数器加 1
done

echo
echo "===== 小节 3：\$? 退出码与 \$\$ 进程号 ====="
ls / > /dev/null 2>&1                           # 执行一条一定成功的命令
echo "ls / 成功后的 \$? = $?"                   # 0 代表成功
ls /这个目录不存在 > /dev/null 2>&1             # 执行一条一定失败的命令
echo "ls 失败后的 \$? = $?"                     # 非 0 代表失败
echo "当前 shell 的进程号 \$\$ = $$"            # $$ 是本 shell 的 PID
sleep 0.1 &                                     # 丢一个后台任务出去
echo "最近一个后台任务的 \$! = $!"              # $! 是它的 PID
wait                                            # 等后台任务结束，避免输出打架

echo
echo "===== 小节 4：shift 左移参数 ====="
echo "左移前：\$1=$1  \$#=$#"                    # 看看当前状态
shift                                           # 丢掉第 1 个参数，后面依次前移
echo "左移后：\$1=$1  \$#=$#"                    # 少了一个参数

# ------------------------------------------------------------
# 运行结果（直接 bash 02-位置参数与特殊变量.sh 即可）：
# ===== 小节 1：\$0 与位置参数 \$1 \$2 =====
# 脚本名 \$0      = 02-位置参数与特殊变量.sh
# 第 1 个参数 \$1 = 苹果
# 第 2 个参数 \$2 = 香蕉
# 第 3 个参数 \$3 = 带 空格 的参数
# 第 10 个参数 \${10} = （没传）
#
# ===== 小节 2：\$# \$@ \$* 与遍历 =====
# 参数个数 \$# = 3
# 所有参数 \$* = [苹果 香蕉 带 空格 的参数]
#   第 1 个参数：[苹果]
#   第 2 个参数：[香蕉]
#   第 3 个参数：[带 空格 的参数]
#
# ===== 小节 3：\$? 退出码与 \$\$ 进程号 =====
# ls / 成功后的 \$? = 0
# ls 失败后的 \$? = 2
# 当前 shell 的进程号 \$\$ = 12345（每台机器、每次运行都不同）
# 最近一个后台任务的 \$! = 12346（同上，只要比 \$\$ 大 1 左右就对了）
#
# ===== 小节 4：shift 左移参数 =====
# 左移前：\$1=苹果  \$#=3
# 左移后：\$1=香蕉  \$#=2
