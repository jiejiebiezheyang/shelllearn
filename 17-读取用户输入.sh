#!/bin/bash
# ============================================
# 序号: 17
# 主题: 读取用户输入（read、-p -t -s）
# 难度: ★★☆
# 前置知识: 01 变量定义与使用、09 数组基础
# 学习目标: 掌握 read 的提示、限时、隐藏、单字符与数组读取
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. 基本用法：read 变量名 —— 从键盘读一行，存进变量（不包含换行符）。
#    读完之后用 $变量名 使用即可。
# 2. 四个最常用选项：
#      -p "提示语"   先打印提示语再等待输入
#                    （提示语走 stderr，而且只在"标准输入是终端"时才显示；
#                      用管道或 <<< 喂数据时看不到提示语，这是正常现象）
#      -t 秒数       限时，超时没输入就返回非 0（可写小数，如 -t 0.5）
#      -s            隐藏输入（输密码专用，不回显）
#      -n 个数       读够指定个数就立刻返回（如 -n 1 读一个字符）
# 3. -r 选项：禁止把反斜杠当转义符，读路径、读文件行时几乎总要加。
# 4. 一次读多个变量：read a b c，输入按空格切开依次赋值，
#    最后一个变量会把剩下的全部吃掉。
# 5. 读进数组：read -a 数组名，输入 "red green blue" 会变成 3 个元素。
# 6. 判断超时/输入结束：if read -t 5 -p "..." x; then ... else ... fi，
#    read 成功返回 0，超时或遇到文件结尾返回非 0。
# 7. read 默认从标准输入读，所以可以配合管道或 <<< （here-string）喂数据。
# ------------------------------------------------------------

echo "===== 小节 1：基本读取（用 here-string 模拟键盘输入） ====="
read -r name <<< "小明"                # <<< 把右边的字符串当成输入喂给 read
echo "读到的名字：$name"
read -r age <<< "18"
echo "读到的年龄：$age"

echo
echo "===== 小节 2：-p 提示语 ====="
# 说明：-p 的提示语只有在"标准输入是终端"时才显示。
# 下面用 <<< 把数据直接喂给 read，输入不是终端，所以看不到提示语；
# 你在终端里手动运行、手动敲键盘时，就能看到"请输入姓名："。
read -r -p "请输入姓名：" user_name <<< "小红"   # -p 先显示提示语再读
echo "你输入的是：$user_name"

echo
echo "===== 小节 3：-s 隐藏输入（密码场景） ====="
read -r -s -p "请输入密码：" password <<< "s3cret"   # -s 不回显输入内容
echo "密码已读取，长度是 ${#password} 个字符（-s 让你敲的内容不显示在屏幕上）"

echo
echo "===== 小节 4：-t 限时输入 ====="
if read -r -t 0.3 -p "请在 0.3 秒内输入点什么：" answer; then
    echo "按时收到输入：$answer"
else
    echo "超时或输入已结束，没有收到内容（read 返回非 0）"
fi

echo
echo "===== 小节 5：-n 读固定字符数 ====="
read -r -n 1 -p "按一个键继续：" key <<< "Y"    # 只读 1 个字符就返回
echo "你按下的键是：[$key]"
read -r -n 3 code <<< "ABC123"                  # 只读 3 个字符
echo "读 3 个字符得到：[$code]"

echo
echo "===== 小节 6：一次读多个变量 ====="
read -r first last <<< "张 三丰"        # 最后一个变量吃掉剩下的全部内容
echo "第一个变量：$first"
echo "第二个变量：$last"
read -r a b <<< "只有一段"              # 输入不够分时，后面的变量为空
echo "a=[$a]  b=[$b]"

echo
echo "===== 小节 7：读进数组 ====="
read -r -a colors <<< "red green blue"  # -a 把输入按空格拆进数组
echo "数组元素个数：${#colors[@]}"
echo "第 2 个元素：${colors[1]}"
echo "全部元素：${colors[@]}"

echo
echo "===== 小节 8：配合管道逐行读取 ====="
printf '第一行\n第二行\n' | while IFS= read -r line; do   # 管道喂给 read
    echo "管道读到：$line"
done

# ------------------------------------------------------------
