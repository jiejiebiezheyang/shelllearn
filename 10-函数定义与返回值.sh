# 前置知识: 02 位置参数与特殊变量、04 条件判断
# 学习目标: 掌握函数定义、传参、return 退出码与 echo 返回字符串
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. 定义函数的两种写法，效果完全一样：
#      say_hi() { echo "hi"; }        # 推荐
#      function say_hi { echo "hi"; } # 也行
#    注意左花括号前要有空格，函数体结束用右花括号。
# 2. 调用函数就是写函数名，和调用普通命令没有区别。
# 3. 函数内部取参数和脚本一模一样：$1 $2 …、$#、$@。
#    函数的 $1 是函数自己的参数，不会和脚本的位置参数打架。
# 4. return 只能返回 0-255 的整数，本质是"退出码"，
#    通常 0 表示成功、非 0 表示失败，配合 if 使用最自然。
# 5. 想返回字符串/大数字，用 echo 打印 + $( ) 捕获：
#      result=$(函数名 参数)
# 6. 不写 return 时，函数的退出码取最后一条命令的退出码。
# 7. 函数必须先定义后调用；函数名后用局部变量请加 local（见第 22 课）。
# ------------------------------------------------------------

echo "===== 小节 1：最简单无参函数 ====="
say_hello() {                        # 函数名() { 函数体 }
    echo "你好，我是一个函数"        # 函数体里的命令
}                                    # 右花括号结束定义
say_hello                            # 调用函数：直接写函数名
say_hello                            # 可以重复调用

echo
echo "===== 小节 2：带参数的函数 ====="
greet() {                            # 定义带参函数
    echo "你好，$1！你今年 $2 岁。"   # 函数内部用 $1 $2 取自己的参数
    echo "本次共收到 $# 个参数"      # $# 也只统计函数自己的参数
}
greet "小明" 18                      # 传参方式和普通命令一样
greet "小红" 20
echo "注意：脚本的位置参数没有被影响，脚本自己收到 $# 个参数"

echo
echo "===== 小节 3：用 return 返回退出码 ====="
is_even() {                          # 判断是否为偶数
    if (( $1 % 2 == 0 )); then       # 取余判断
        return 0                     # 0 表示"真/成功"
    else
        return 1                     # 1 表示"假/失败"
    fi
}
if is_even 4; then
    echo "is_even 4 返回 0，if 判为真：4 是偶数"
fi
if ! is_even 5; then
    echo "is_even 5 返回 1，if 判为假：5 不是偶数"
fi
is_even 8
echo "is_even 8 的退出码 = $?"       # 马上用 $? 取退出码
is_even 7
echo "is_even 7 的退出码 = $?"

echo
echo "===== 小节 4：用 echo + \$( ) 返回字符串 ====="
add() {                              # 加法函数
    echo $(( $1 + $2 ))              # 把结果打印到标准输出
}
sum=$(add 3 5)                       # $( ) 把打印内容捕获成字符串
echo "add 3 5 的结果：$sum"
echo "结果再乘 2：$(( sum * 2 ))"     # 拿到的值可以直接参与计算
echo "嵌套调用：add 10 \$(add 1 2) = $(add 10 $(add 1 2))"

echo
echo "===== 小节 5：return 的取值范围 ====="
big() {
    return 300                       # 超过 255 会被 bash 取模
}
big
echo "return 300 实际得到的退出码：$?（= 300 - 256）"
small() {
    return -1                        # 负数也会被换算
}
small
echo "return -1 实际得到的退出码：$?（= 256 - 1）"

# ------------------------------------------------------------
# 运行结果：
# ===== 小节 1：最简单无参函数 =====
# 你好，我是一个函数
# 你好，我是一个函数
#
# ===== 小节 2：带参数的函数 =====
# 你好，小明！你今年 18 岁。
# 本次共收到 2 个参数
# 你好，小红！你今年 20 岁。
# 本次共收到 2 个参数
# 注意：脚本的位置参数没有被影响，脚本自己收到 0 个参数
#
# ===== 小节 3：用 return 返回退出码 =====
# is_even 4 返回 0，if 判为真：4 是偶数
# is_even 5 返回 1，if 判为假：5 不是偶数
# is_even 8 的退出码 = 0
# is_even 7 的退出码 = 1
#
# ===== 小节 4：用 echo + $( ) 返回字符串 =====
# add 3 5 的结果：8
# 结果再乘 2：16
# 嵌套调用：add 10 $(add 1 2) = 13
#
# ===== 小节 5：return 的取值范围 =====
# return 300 实际得到的退出码：44（= 300 - 256）
# return -1 实际得到的退出码：255（= 256 - 1）
