#!/bin/bash
# ============================================
# 序号: 06
# 主题: 数值比较与逻辑运算
# 难度: ★★☆
# 前置知识: 04 条件判断
# 学习目标: 掌握 -eq -gt 等数值比较符与 && || ! 逻辑运算
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. [ ] 里比较数字必须用专用运算符，一共六个：
#      -eq 等于    -ne 不等于
#      -gt 大于    -lt 小于
#      -ge 大于等于 -le 小于等于
# 2. 千万不能在 [ ] 里写 > 和 <：> 会被 shell 当成"输出重定向"，
#    结果既比错了大小，还会凭空生成一个文件名很怪的文件。
# 3. (( )) 是算术环境，里面可以直接用 > < >= <= == !=，
#    还能做加减乘除取余，写起来最像数学，推荐使用。
# 4. 逻辑运算三种写法：
#      · 命令之间用 && （前面成功才做后面）和 || （前面失败才做后面）
#      · [[ ]] 或 (( )) 内部直接写 && ||
#      · 取反用 !，例如 if ! [ -f x ]
# 5. && 和 || 是"短路"的：左边结果已经能决定胜负时，右边不执行。
# 6. 小技巧：条件是一行命令时，可以写 [ 条件 ] && 命令，省略 if。
# ------------------------------------------------------------

echo "===== 小节 1：六个数值比较运算符 ====="
a=10                                     # 被比较的第一个数
b=3                                      # 被比较的第二个数
echo "当前 a=$a  b=$b"
if [ "$a" -eq "$b" ]; then echo "$a -eq $b ：相等"; else echo "$a -eq $b ：不相等"; fi
if [ "$a" -ne "$b" ]; then echo "$a -ne $b ：不相等"; fi
if [ "$a" -gt "$b" ]; then echo "$a -gt $b ：a 比 b 大"; fi
if [ "$b" -lt "$a" ]; then echo "$b -lt $a ：b 比 a 小"; fi
if [ "$a" -ge 10 ]; then echo "$a -ge 10 ：a 至少是 10"; fi
if [ "$b" -le 3 ]; then echo "$b -le 3 ：b 最多是 3"; fi

echo
echo "===== 小节 2：(( )) 算术比较（推荐） ====="
x=8                                      # 第一个整数
y=15                                     # 第二个整数
if (( x < y )); then echo "(( ))：$x < $y 成立"; fi
if (( y % 3 == 0 )); then echo "(( ))：$y 能被 3 整除"; fi
if (( x > 5 && y > 10 )); then echo "(( ))：x>5 且 y>10 同时成立"; fi
if (( x == 8 || y == 8 )); then echo "(( ))：x==8 或 y==8 至少一个成立"; fi
(( x++ ))                                # (( )) 里还能直接自增
echo "自增后 x = $x"

echo
echo "===== 小节 3：必须避开的坑 ====="
n=5
# if [ $n > 3 ]; then echo 成立; fi      # 错误示范：> 变成了重定向
echo "[ ] 里比较数字不能用 > < ，必须用 -gt -lt"
if [ "$n" -gt 3 ]; then echo "正确写法：$n -gt 3 成立"; fi
if (( n > 3 )); then echo "(( )) 里可以直接写 n > 3"; fi

echo
echo "===== 小节 4：&& 与 || 短路运算 ====="
[ -d /tmp ] && echo "/tmp 是目录（&& 左边成立才执行右边）"
[ -d /这个目录不存在 ] || echo "目录不存在（|| 左边失败才执行右边）"
[ -d /tmp ] && [ -w /tmp ] && echo "/tmp 既存在又可写（多个 && 串起来）"
if ! [ -d /这个目录不存在 ]; then echo "! 取反：它确实不是目录"; fi

echo
echo "===== 小节 5：一行式条件 ====="
age=20                                    # 用一行式做三元判断
[ "$age" -ge 18 ] && echo "成年" || echo "未成年"

# ------------------------------------------------------------
# 运行结果：
# ===== 小节 1：六个数值比较运算符 =====
# 当前 a=10  b=3
# 10 -eq 3 ：不相等
# 10 -ne 3 ：不相等
# 10 -gt 3 ：a 比 b 大
# 3 -lt 10 ：b 比 a 小
# 10 -ge 10 ：a 至少是 10
# 3 -le 3 ：b 最多是 3
#
# ===== 小节 2：(( )) 算术比较（推荐） =====
# (( ))：8 < 15 成立
# (( ))：15 能被 3 整除
# (( ))：x>5 且 y>10 同时成立
# (( ))：x==8 或 y==8 至少一个成立
# 自增后 x = 9
#
# ===== 小节 3：必须避开的坑 =====
# [ ] 里比较数字不能用 > < ，必须用 -gt -lt
# 正确写法：5 -gt 3 成立
# (( )) 里可以直接写 n > 3
#
# ===== 小节 4：&& 与 || 短路运算 =====
# /tmp 是目录（&& 左边成立才执行右边）
# 目录不存在（|| 左边失败才执行右边）
# /tmp 既存在又可写（多个 && 串起来）
# ! 取反：它确实不是目录
#
# ===== 小节 5：一行式条件 =====
# 成年
# ------------------------------------------------------------
