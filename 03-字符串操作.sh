# 加空格相连 : Hello World
# 带标点拼接 : Hello, World!
# 数字拼接   : 第 3 名
#
# ===== 小节 2：字符串长度 =====
# 字符串内容 : Shell脚本
# 字符数 ${#word} = 7
# 空串长度   : 0
#
# ===== 小节 3：字符串截取 =====
# 原字符串     : /home/user/data/report.txt
# 前 5 个字符   : /home
# 从第 6 个到结尾: /user/data/report.txt
# 最后 3 个字符 : txt
# 去掉尾部 4 个 : /home/user/data/report
#
# ===== 小节 4：字符串替换 =====
# 原文        : 我爱吃苹果，苹果真好吃，苹果不贵
# 替换第一次  : 我爱吃香蕉，苹果真好吃，苹果不贵
# 替换全部    : 我爱吃香蕉，香蕉真好吃，香蕉不贵
# 删除所有苹果: 我爱吃，真好吃，不贵
# 删掉所有数字: abc
#
# ===== 小节 5：大小写与默认值 =====
# 全大写      : HELLO SHELL
# 全小写      : hello shell
# 取默认值    : 我是默认值
