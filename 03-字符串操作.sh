# ------------------------------------------------------------
# 【知识点讲解】
# 1. 拼接：把两个变量写在一起就行，不需要 + 号。
#      big="$a$b"    或    big="${a} ${b}"
#    注意中间想加分隔符（空格、逗号）必须自己写出来。
# 2. 长度：${#变量} 返回字符个数，中文按"字符"数，不是字节数。
# 3. 截取：${变量:起始下标:长度}
#      · 下标从 0 开始；省略长度表示取到结尾。
#      · 负数表示从右边数，冒号后必须留一个空格：${s: -3}
# 4. 替换：
#      · ${变量/旧/新}   只替换第一次出现
#      · ${变量//旧/新}  替换全部出现
#      · 旧串支持通配符，如 ${s//[0-9]/} 可删除所有数字
# 5. 大小写转换（bash 4 及以上）：
#      ${变量^^} 全部变大写，${变量,,} 全部变小写。
# 6. 取默认值：${变量:-默认值}，变量为空时用默认值，原变量不变。
#    以上操作都不会修改原变量，只是"算出一份新字符串"返回给你。
# ------------------------------------------------------------

echo "===== 小节 1：字符串拼接 ====="
first="Hello"                       # 第一个片段
second="World"                      # 第二个片段
echo "直接相连   : $first$second"                     # 中间没有任何分隔
echo "加空格相连 : $first $second"                    # 空格要自己写
greeting="${first}, ${second}!"                       # 用花括号拼接更清晰
echo "带标点拼接 : $greeting"                         # 拼好的完整句子
num=3                                                 # 数字也能拼进字符串
echo "数字拼接   : 第 ${num} 名"                      # 建议数字也加花括号

echo
echo "===== 小节 2：字符串长度 ====="
word="Shell脚本"                    # 7 个字符：S h e l l 脚 本
echo "字符串内容 : $word"
echo "字符数 \${#word} = ${#word}"   # ${#变量} 得到长度
empty=""                                              # 定义一个空串
echo "空串长度   : ${#empty}"                         # 空串长度是 0

echo
echo "===== 小节 3：字符串截取 ====="
path="/home/user/data/report.txt"   # 准备一个长字符串
echo "原字符串     : $path"
echo "前 5 个字符   : ${path:0:5}"    # 从下标 0 开始取 5 个
echo "从第 6 个到结尾: ${path:5}"     # 只给起始下标，取到结尾
echo "最后 3 个字符 : ${path: -3}"    # 负数从右边数，冒号后要有空格
echo "去掉尾部 4 个 : ${path:0:${#path}-4}"   # 长度也可以是个表达式

echo
echo "===== 小节 4：字符串替换 ====="
text="我爱吃苹果，苹果真好吃，苹果不贵"   # 里面出现了 3 次"苹果"
echo "原文        : $text"
echo "替换第一次  : ${text/苹果/香蕉}"     # 单斜杠只换第一个
echo "替换全部    : ${text//苹果/香蕉}"    # 双斜杠换掉所有
echo "删除所有苹果: ${text//苹果/}"         # 替换成空串就等于删除
code="a1b2c3"                              # 混了数字的字符串
echo "删掉所有数字: ${code//[0-9]/}"        # 旧串支持通配符

echo
echo "===== 小节 5：大小写与默认值 ====="
mixed="Hello Shell"                        # 大小写混合
echo "全大写      : ${mixed^^}"             # ^^ 转大写
echo "全小写      : ${mixed,,}"             # ,, 转小写
unset notset                               # 故意准备一个没定义的变量
echo "取默认值    : ${notset:-我是默认值}"   # 为空时显示默认值

# ------------------------------------------------------------
# 运行结果：
