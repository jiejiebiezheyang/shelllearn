#!/bin/bash
# ============================================
# 序号: 26
# 主题: 日志分析与统计脚本
# 难度: ★★★
# 前置知识: 12 管道与文本处理入门、25 文本处理进阶
# 学习目标: 用 grep/awk/sort/uniq 组合出一份完整的日志分析报告
# ============================================

# ------------------------------------------------------------
# 【知识点讲解】
# 1. 日志分析的核心套路只有一句话：
#      按行过滤（grep）-> 取出某一列（awk）-> 排序计数（sort | uniq -c）
# 2. sort | uniq -c 是"统计频次"的黄金组合，顺序不能反：
#      · uniq 只能合并"相邻"的重复行，所以必须先 sort；
#      · uniq -c 会在每行前面加上出现次数。
#    想按次数从多到少排，再接一个 sort -rn。
# 3. 并列名次不稳定怎么办？加次级排序键：
#      sort -k1,1nr -k2,2   先按第 1 列数字降序，再按第 2 列升序
#    这样结果就固定了，脚本输出可复现。
# 4. awk 的数值技巧：像 "320ms" 这种带单位的字段，
#    awk 会自动取前面的数字参与运算，所以 $8+0 > 300 直接就能用。
# 5. 常用统计命令速查：
#      wc -l                      总行数
#      grep -c '关键字'           匹配行数
#      awk '{print $3}' | sort | uniq -c   按第 3 列分组计数
#      head -3 / tail -5          取前几名 / 最后几行
# 6. 好习惯：把报告用 { ... } > report.txt 一次性落盘，
#    既能在屏幕上看，又能存档、发邮件。
# 7. 本脚本的日志是自己当场生成的，不依赖任何外部文件。
# ------------------------------------------------------------

logfile=$(mktemp)                      # 自建一份"服务器日志"
cat > "$logfile" <<'EOF'
2024-05-01 08:01:12 INFO  192.168.1.10 GET /index.html 200 12ms
2024-05-01 08:02:35 INFO  192.168.1.11 GET /about.html 200 18ms
2024-05-01 08:05:02 ERROR 192.168.1.10 POST /login 500 320ms
2024-05-01 08:07:44 WARN  192.168.1.12 GET /api/data 404 25ms
2024-05-01 08:10:11 INFO  192.168.1.10 GET /index.html 200 11ms
2024-05-01 08:12:30 ERROR 192.168.1.13 POST /order 500 450ms
2024-05-01 08:15:55 INFO  192.168.1.11 GET /about.html 200 17ms
2024-05-01 08:18:20 WARN  192.168.1.14 GET /api/list 404 22ms
2024-05-01 08:20:45 INFO  192.168.1.10 GET /index.html 200 10ms
2024-05-01 08:25:03 ERROR 192.168.1.10 GET /api/data 500 380ms
2024-05-01 08:30:00 INFO  192.168.1.12 GET /index.html 200 13ms
2024-05-01 08:35:12 INFO  192.168.1.15 GET /contact 200 19ms
EOF
echo "已生成测试日志：$logfile"
echo "日志格式：日期 时间 级别 客户端IP 方法 路径 状态码 耗时"

echo
echo "===== 小节 1：整体概览 ====="
total=$(wc -l < "$logfile")            # 总行数
echo "总行数    : $total"
echo "起始时间  : $(head -1 "$logfile" | awk '{print $1" "$2}')"
echo "结束时间  : $(tail -1 "$logfile" | awk '{print $1" "$2}')"
echo "涉及 IP   : $(awk '{print $4}' "$logfile" | sort -u | wc -l) 个不同的客户端"

echo
echo "===== 小节 2：按日志级别统计 ====="
awk '{print $3}' "$logfile" | sort | uniq -c | sort -rn
echo "（从多到少排列：INFO 最多，说明整体还算健康）"

echo
echo "===== 小节 3：按状态码统计 ====="
awk '{print $7}' "$logfile" | sort | uniq -c | sort -rn
echo "（200 是正常，404 是找不到页面，500 是服务端错误）"

echo
echo "===== 小节 4：访问量 TOP 3 的客户端 ====="
awk '{print $4}' "$logfile" | sort | uniq -c | sort -k1,1nr -k2,2 | head -3
echo "（sort -k1,1nr -k2,2 的意思是「次数降序、IP 升序」，避免并列时顺序乱跳）"

echo
echo "===== 小节 5：慢请求明细（耗时超过 300ms） ====="
awk '$8 + 0 > 300 {print "  " $2, $4, $6, $8}' "$logfile"
echo "（awk 会自动把 320ms 里的 320 取出来当数字比较）"

echo
echo "===== 小节 6：错误日志明细 ====="
grep 'ERROR' "$logfile" | sed 's/^/  /'
echo "错误总条数：$(grep -c 'ERROR' "$logfile")"

echo
echo "===== 小节 7：生成一份报告文件 ====="
work=$(mktemp -d)                      # 单独建个目录放报告
report="$work/report.txt"
{
    echo "========== 日志分析报告 =========="
    echo "日志文件 : $logfile"
    echo "生成时间 : $(date '+%F %T')"
    echo "总行数   : $total"
    echo "----------------------------------"
    echo "【按级别统计】"
    awk '{print $3}' "$logfile" | sort | uniq -c | sort -rn | sed 's/^/  /'
    echo "【按状态码统计】"
    awk '{print $7}' "$logfile" | sort | uniq -c | sort -rn | sed 's/^/  /'
    echo "----------------------------------"
    echo "【访问量 TOP3 客户端】"
    awk '{print $4}' "$logfile" | sort | uniq -c | sort -k1,1nr -k2,2 | head -3 | sed 's/^/  /'
    echo "=================================="
} > "$report"                          # 整段输出重定向进报告文件
cat "$report"                          # 再打印到屏幕上
echo "报告文件：$report（共 $(wc -l < "$report") 行）"

rm -rf "$work" "$logfile"              # 清理
echo
echo "临时文件和报告已清理"

