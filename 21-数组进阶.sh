# ------------------------------------------------------------
# 【知识点讲解】
# 1. 切片：${数组[@]:起始下标:个数}
#      ${nums[@]:1:2}   从下标 1 开始取 2 个
#      ${nums[@]:2} 取到结尾；${nums[@]: -2} 取最后 2 个（负号前要空格）
# 2. 复制数组必须写 array2=("${array1[@]}")。
#    只写 array2=$array1 得到的是"下标 0 那一个元素"，不是整个数组。
# 3. 合并数组：array3=("${a[@]}" "${b[@]}")，追加：a+=(新元素)。
# 4. 删除：unset 'arr[下标]' 删一个元素（注意加引号，
#    否则可能被 shell 当成通配符）；unset arr 删掉整个数组。
#    删除后数组会变成"稀疏"的，下标不会自动重排。
# 5. 关联数组（类似其他语言的字典/哈希表）：
#      declare -A map        # 必须先声明，-A = associative
#      map[键]=值             # 用字符串做下标
#      ${map[键]}            # 取值
#      ${!map[@]}            # 所有键
#      ${map[@]}             # 所有值
#      unset 'map[键]'       # 删一个键值对
# 6. 关联数组的键顺序是"哈希顺序"，不确定！
#    想稳定输出就先 sort 一下，或者按固定顺序遍历。
# 7. 判断键是否存在：[[ -v map[键] ]]（bash 4.2+），
#    或者用 [[ -n "${map[键]:-}" ]] 兼容性更好。
# ------------------------------------------------------------

echo "===== 小节 1：数组切片 ====="
nums=(10 20 30 40 50)                  # 准备一个 5 个元素的数组
echo "全部元素        : ${nums[@]}"
echo "从下标 1 取 2 个 : ${nums[@]:1:2}"     # 20 30
echo "从下标 2 到结尾  : ${nums[@]:2}"       # 30 40 50
echo "最后 2 个元素    : ${nums[@]: -2}"     # 负号前必须有空格
echo "下标越界也不会报错：${nums[@]:10:2}（空）"

echo
echo "===== 小节 2：复制、追加与合并 ====="
a=(1 2 3)                              # 原数组
b=("${a[@]}")                          # 正确复制：必须带引号和 [@]
wrong=$a                               # 错误示范：只拿到第 0 个元素
b+=(4 5)                               # 在副本上追加
c=("${a[@]}" "${b[@]}")                # 两个数组合并成一个
echo "a      = ${a[@]}"
echo "错误复制 wrong = [$wrong]"
echo "正确复制 b = ${b[@]}"
echo "合并结果 c = ${c[@]}"

echo
echo "===== 小节 3：删除元素与稀疏数组 ====="
arr=(A B C D E)                        # 五个字母
echo "删除前：${arr[@]}  下标：${!arr[@]}"
unset 'arr[2]'                         # 删掉下标 2，记得加引号
echo "删除下标 2 后：${arr[@]}"
echo "下标变成：${!arr[@]}   <-- 注意下标 2 空了，没有自动前移"
echo "长度：${#arr[@]}"
arr+=(F)                               # 追加会补到最大下标之后
echo "追加 F 后：${arr[@]}  下标：${!arr[@]}"
unset arr                              # 删掉整个数组
echo "整个删除后长度：${#arr[@]}"

echo
echo "===== 小节 4：关联数组的增删查改 ====="
declare -A user                        # 声明关联数组（-A 不能忘）
user[name]="小明"                       # 用字符串当键
user[age]=18
user[city]="北京"
echo "name = ${user[name]}"            # 按键取值
echo "age  = ${user[age]}"
user[age]=19                           # 同一个键再赋值就是修改
echo "修改后 age = ${user[age]}"
echo "所有键：${!user[@]}"
echo "所有值：${user[@]}"
unset 'user[city]'                     # 删掉一个键值对
echo "删除 city 后所有键：${!user[@]}"

echo
echo "===== 小节 5：遍历关联数组 ====="
declare -A conf
conf[host]="192.168.1.10"
conf[port]="8080"
conf[user]="admin"
echo "-- 按键的字母顺序排序后遍历（保证输出稳定） --"
for k in $(printf '%s\n' "${!conf[@]}" | sort); do
    echo "  $k = ${conf[$k]}"
done
echo "-- 判断键是否存在 --"
if [[ -n "${conf[host]:-}" ]]; then
    echo "  conf 里有 host 这个键，值是 ${conf[host]}"
fi
if [[ -z "${conf[password]:-}" ]]; then
    echo "  conf 里没有 password 这个键"
fi

echo
echo "===== 小节 6：用关联数组做词频统计 ====="
declare -A count                       # 键=词，值=出现次数
for w in 苹果 香蕉 苹果 橙子 苹果 香蕉; do
    (( count[$w]++ ))                  # 对应键的计数加 1
done
for w in 苹果 香蕉 橙子; do            # 按固定顺序输出，结果才稳定
    echo "  $w 出现 ${count[$w]} 次"
done

# ------------------------------------------------------------
# 运行结果：
# ===== 小节 1：数组切片 =====
# 全部元素        : 10 20 30 40 50
# 从下标 1 取 2 个 : 20 30
# 从下标 2 到结尾  : 30 40 50
# 最后 2 个元素    : 40 50
# 下标越界也不会报错：（空）
#
# ===== 小节 2：复制、追加与合并 =====
# a      = 1 2 3
# 错误复制 wrong = [1]
# 正确复制 b = 1 2 3 4 5
# 合并结果 c = 1 2 3 1 2 3 4 5
#
# ===== 小节 3：删除元素与稀疏数组 =====
# 删除前：A B C D E  下标：0 1 2 3 4
# 删除下标 2 后：A B D E
# 下标变成：0 1 3 4   <-- 注意下标 2 空了，没有自动前移
# 长度：4
# 追加 F 后：A B D E F  下标：0 1 3 4 5
# 整个删除后长度：0
#
# ===== 小节 4：关联数组的增删查改 =====
# name = 小明
# age  = 18
# 修改后 age = 19
# 所有键：city age name   <-- 哈希顺序，不同机器/不同 bash 可能不一样
# 所有值：北京 19 小明     <-- 值的顺序和键一一对应，但顺序同样不固定
# 删除 city 后所有键：age name
#
# ===== 小节 5：遍历关联数组 =====
# -- 按键的字母顺序排序后遍历（保证输出稳定） --
#   host = 192.168.1.10
#   port = 8080
#   user = admin
# -- 判断键是否存在 --
#   conf 里有 host 这个键，值是 192.168.1.10
#   conf 里没有 password 这个键
#
# ===== 小节 6：用关联数组做词频统计 =====
